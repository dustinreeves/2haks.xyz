// Design model <-> Jinja Orchestrator files.
//
// model = {
//   release: '7.4',
//   options:  { cert_auth: false, lo_summary: '10.200.0.0/14', ... },   // project-level `{% set x = ... %}`
//   regions:  { West: { as, lan_summary, lo_summary, vrfs: [...], hubs: [...] } },
//   profiles: { Name: { ha, options: {}, bridges: [], interfaces: [ {...} ] } },
//   hubs:     { 'site1-H1': { lo_bgp, hub_name, peering: {}, overlays: { ISP1: { wan_ip, network_id, hub2hub } } } },
//   inventory:{ defaults: {}, Hub: { name: { hostname, ... } }, Edge: { ... } }
// }
// Any value may be a variable reference {"$var": "isp1_intf"}: it is emitted bare, so the
// orchestrator resolves it per device from the inventory.

export const STRUCTURAL = ['regions', 'profiles', 'hubs'];
export const isRef = v => v !== null && typeof v === 'object' && !Array.isArray(v) && typeof v.$var === 'string';
export const ref = name => ({ $var: name });

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

function str(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n') + "'";
}

function inline(v) {
  if (isRef(v)) return IDENT.test(v.$var) ? v.$var : 'none';
  if (typeof v === 'string') return str(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (v === null || v === undefined) return 'none';
  if (Array.isArray(v)) return '[ ' + v.map(inline).join(', ') + ' ]';
  return '{ ' + Object.entries(v).map(([k, x]) => str(k) + ': ' + inline(x)).join(', ') + ' }';
}

const isScalar = v => v === null || typeof v !== 'object' || isRef(v);

// Pretty-print a Jinja/Python literal. Arrays of scalars stay on one line.
export function literal(v, depth = 0) {
  const pad = '  '.repeat(depth + 1), end = '  '.repeat(depth);
  if (isScalar(v)) return inline(v);
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    if (v.every(isScalar)) return inline(v);
    return '[\n' + v.map(x => pad + literal(x, depth + 1)).join(',\n') + '\n' + end + ']';
  }
  const ent = Object.entries(v).filter(([, x]) => x !== undefined);
  if (!ent.length) return '{}';
  return '{\n' + ent.map(([k, x]) => pad + str(k) + ': ' + literal(x, depth + 1)).join(',\n') + '\n' + end + '}';
}

const clean = (obj, drop = v => v === undefined || v === '') => {
  if (Array.isArray(obj)) return obj.map(x => clean(x, drop));
  if (obj && typeof obj === 'object' && !isRef(obj)) {
    const o = {};
    for (const [k, v] of Object.entries(obj)) if (!drop(v)) o[k] = clean(v, drop);
    return o;
  }
  return obj;
};

export function emitProject(model, { header = true } = {}) {
  const out = [];
  if (header) {
    out.push('{# Project Template: generated by the SD-WAN ADVPN Designer #}');
    out.push('{# Jinja Orchestrator ' + (model.release || '7.4') + ' (Fortinet), design flavor "Dynamic BGP on Loopback" #}');
    out.push('{# Per-device variables (e.g. isp1_intf) are resolved from the inventory file #}\n');
  }
  for (const [k, v] of Object.entries(model.options || {})) {
    if (v === undefined || v === '') continue;
    if (!IDENT.test(k)) continue;
    out.push('{% set ' + k + ' = ' + literal(v) + ' %}');
  }
  out.push('');
  for (const k of STRUCTURAL) {
    const val = clean(model[k] || {});
    out.push('{# ' + { regions: 'Regions', profiles: 'Device Profiles', hubs: 'Hubs' }[k] + ' #}');
    out.push('{% set ' + k + ' = ' + literal(val) + '\n%}\n');
  }
  return out.join('\n');
}

export function emitInventory(inv) {
  const o = {};
  if (inv.defaults && Object.keys(inv.defaults).length) o.defaults = inv.defaults;
  for (const g of Object.keys(inv)) if (g !== 'defaults') o[g] = inv[g];
  return JSON.stringify(clean(o), null, 2) + '\n';
}

// Project Template variables (as returned by engine.parse_project) -> model
export function modelFromVars(vars, inventory, release = '7.4') {
  const m = { release, options: {}, regions: {}, profiles: {}, hubs: {}, inventory: inventory || { defaults: {}, Hub: {}, Edge: {} } };
  for (const [k, v] of Object.entries(vars)) {
    if (STRUCTURAL.includes(k)) m[k] = v; else m.options[k] = v;
  }
  return m;
}

export function parseInventory(text) {
  const inv = JSON.parse(text);
  inv.defaults ||= {};
  return inv;
}

// All per-device variables a design references (profiles + hubs), so the inventory table
// can offer the right columns.
export function referencedVars(model) {
  const s = new Set();
  const walk = v => {
    if (isRef(v)) s.add(v.$var);
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  };
  walk(model.profiles); walk(model.hubs); walk(model.regions); walk(model.options);
  return [...s];
}
